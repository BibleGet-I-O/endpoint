-- 040: BLPD section headings and Psalm 119's stanza letters.
--
-- vatican.va (archive/ESL0506) prints BLPD's section headings, which BibleGet's
-- BLPD lacked: higher-level headings ("Enunciado", e.g. "Desde Adán hasta el
-- Diluvio") and section headings ("Titulointerior"), plus Psalm 119's stanza
-- letters (Alef, Bet, ...; stored without brackets, as NABRE and CEI 2008 store
-- theirs). They go into title1-title3 in printed order, before the verse they
-- introduce, or mid-verse with a title_position where the heading interrupts a
-- verse (23 verses), as for NABRE in 029. Psalm numbers ("SALMO 119") and book
-- and chapter titles are left out. A few misprints in vatican.va's headings are
-- corrected (e.g. "Abrám" -> "Abram" as the verse text spells it, "ombre" ->
-- "hombre"); the list is in the archive's reports/heading-fixes.tsv.
--
-- The headings are the edition's text (© Fundación Palabra de Vida / Editorial
-- Verbo Divino), so the data half lives in the private archive
-- BibleGet-I-O/BLPD-vatican: apply its migrations/040-blpd-headings.sql FIRST
-- (generated by scripts/headings.py and scripts/migration_headings.py). This
-- public half checks the result. Headings are not part of the embedded text:
-- no re-embedding.

DO $mig$
DECLARE
    digest TEXT;
    n INT;
BEGIN
    SELECT md5(string_agg(concat_ws('|', "verseID", coalesce(title1, ''), coalesce(title2, ''), coalesce(title3, ''),
                                    coalesce(title_position::text, '')), E'\n' ORDER BY "verseID")), count(*)
    INTO digest, n
    FROM "BLPD" WHERE coalesce(title1, '') <> '' OR coalesce(title2, '') <> '' OR coalesce(title3, '') <> '';
    IF digest IS DISTINCT FROM '19c4f7c8b36edad73028af81dcd5b576' OR n <> 1245 THEN
        RAISE EXCEPTION 'BLPD headings are not the archive''s (% rows, md5 %): apply BLPD-vatican/migrations/040-blpd-headings.sql first', n, digest;
    END IF;
    RAISE NOTICE 'BLPD: % verses with headings, as in the archive', n;
END
$mig$;
