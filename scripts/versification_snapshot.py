#!/usr/bin/env python3
"""Write or check the verse-structure snapshots in tests/fixtures/versification/.

A snapshot records, for one edition, every verse label in reading order
(sort_order), without any text, so it can be public even for
copyrighted editions. One line per run of rows that share book, chapter and
text_tradition:

    1 31: 1-54
    29 10: 1-17,18a,19,18b,20-34
    19 1 HEBREW: 1-22
    19 1 GREEK: 1a,1b,...,1r,1-22

A label is verse_label when the edition prints one (NABRE "12:1" at the end
of Wis 11, Esther's "A:1"; "·" for a part printed without a number), else
the verse number with its printed letter (verse_segment: "18a"), else the
verse number; alternate numberings (alt_ref) are ignored. Consecutive
numbers are written as ranges. Rows are grouped by the chapter they are
printed under.

The snapshots are what tests/Unit/Data/VersificationCasesTest.php checks
the documented edge cases (tests/fixtures/versification/cases.json)
against, so CI catches a case whose data changed. --check compares a
database with the committed snapshots (and, without --version, reports a
committed snapshot whose edition is no longer in the database): run it after applying a migration
that touches verse rows, and regenerate (without --check) only when the
change is intended; the diff then shows exactly what moved.

Usage:
    python3 scripts/versification_snapshot.py                 # write all editions
    python3 scripts/versification_snapshot.py --check         # exit 1 on any difference
    python3 scripts/versification_snapshot.py --version NABRE

Environment: DB_HOST, DB_PORT, DB_NAME, DB_USER, DB_PASS (as compute_embeddings.py).
"""

import argparse
import difflib
import os
import sys
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "versification"
UNNUMBERED = "·"  # a part printed without a verse number (verse_label '')


def get_connection():
    import psycopg2  # imported here so --help works without it

    return psycopg2.connect(
        host=os.environ.get("DB_HOST", "127.0.0.1"),
        port=os.environ.get("DB_PORT", "5432"),
        dbname=os.environ.get("DB_NAME", "bibleget"),
        user=os.environ.get("DB_USER", "bibleget"),
        password=os.environ.get("DB_PASS", "bibleget"),
    )


def editions(conn):
    """Every table listed in versions_available."""
    with conn.cursor() as cur:
        cur.execute("SELECT sigla FROM versions_available ORDER BY sigla")
        return [r[0] for r in cur.fetchall()]


def has_column(conn, table, column):
    with conn.cursor() as cur:
        cur.execute(
            "SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' "
            "AND table_name = %s AND column_name = %s",
            (table, column),
        )
        return cur.fetchone() is not None


def rows(conn, table):
    """(book, printed chapter, verse, verse_segment, text_tradition, verse_label) in reading order."""
    origin = "coalesce(text_tradition, '')"
    placed = has_column(conn, table, "printed_chapter")
    chapter = "coalesce(printed_chapter, chapter)" if placed else "chapter"
    vlabel = "verse_label" if placed else "NULL"
    with conn.cursor() as cur:
        cur.execute(
            f'SELECT book, {chapter}, verse, coalesce(verse_segment, \'\'), {origin}, {vlabel} '
            f'FROM "{table}" ORDER BY sort_order'
        )
        return cur.fetchall()


def label(verse, segment, verse_label=None):
    """The label the edition prints: verse_label when set ('' = printed without a
    number, written ·), else the number with its printed letter (verse_segment)."""
    if verse_label is not None:
        return verse_label if verse_label != "" else UNNUMBERED
    return f"{verse}{segment}"


def self_test():
    assert label(1, "", None) == "1"
    assert label(1, "", "") == UNNUMBERED
    assert label(1, "", "10:1") == "10:1"
    assert label(18, "a", None) == "18a"
    assert label(17, "aa", None) == "17aa"
    assert label(22, "", None) == "22"
    assert label(1, "a", "A:1") == "A:1"
    print("self-test ok")


def compress(labels):
    """["1", "2", "3", "5a", "6"] -> "1-3,5a,6"."""
    out, start, prev = [], None, None
    for lab in labels + [None]:
        if lab is not None and lab.isdigit() and prev is not None and prev.isdigit() and int(lab) == int(prev) + 1:
            prev = lab
            continue
        if start is not None:
            out.append(start if start == prev else f"{start}-{prev}")
        start = prev = lab
    return ",".join(out)


def snapshot(edition, data):
    lines, key, labels = [f"# {edition}: verse labels in reading order. Generated by "
                         "scripts/versification_snapshot.py; do not edit by hand."], None, []
    for book, chapter, verse, segment, origin, verse_label in data:
        k = (book, chapter, origin)
        if k != key and key is not None:
            lines.append(f"{' '.join(str(x) for x in key if x != '')}: {compress(labels)}")
            labels = []
        key = k
        labels.append(label(verse, segment, verse_label))
    if key is not None:
        lines.append(f"{' '.join(str(x) for x in key if x != '')}: {compress(labels)}")
    return "\n".join(lines) + "\n"


def stale_snapshots(out_dir, names):
    """Committed snapshot files whose edition is not in `names` (e.g. a removed edition)."""
    return [p for p in sorted(out_dir.glob("*.txt")) if p.stem not in names]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the committed snapshots; exit 1 on a difference")
    ap.add_argument("--version", help="only this edition")
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR)
    ap.add_argument("--self-test", action="store_true", help="check the labelling rules and exit")
    args = ap.parse_args()
    if args.self_test:
        self_test()
        return

    conn = get_connection()
    failed = False
    names = [args.version] if args.version else editions(conn)
    for edition in names:
        text = snapshot(edition, rows(conn, edition))
        path = args.out_dir / f"{edition}.txt"
        if not args.check:
            path.write_text(text, encoding="utf-8")
            print(f"{edition}: wrote {path}", file=sys.stderr)
            continue
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if old != text:
            failed = True
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(True), text.splitlines(True), f"{edition}.txt (committed)", f"{edition} (database)"))
        else:
            print(f"{edition}: matches", file=sys.stderr)
    if args.check and not args.version:
        for path in stale_snapshots(args.out_dir, names):
            failed = True
            print(f"{path.name}: committed snapshot, but {path.stem} is not in versions_available")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
