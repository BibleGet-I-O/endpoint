#!/usr/bin/env python3
"""Generate migrations/038-cei2008-esther-repairs.sql from the bibbiaedu.it archive.

CEI 2008's Esther in our table (#185): 11 rows were damaged on import (cut
short, mostly right before an accented letter such as "Purìm"; 1:5 HEBREW
with 1:6's text appended; 7:4 GREEK spliced with 7:5; 8:1 GREEK holding 8:2's
text too), three verses were missing (8:2 in both the Greek and the Hebrew
text, Hebrew 9:30), and 1:3 GREEK has a typo ("dei Persiani e i dei Medi").
format_cei2008_from_source.py --books Est reports exactly these 12 rows
as unmatched or with different wording, and the 3 site verses with no row.

The migration:
  * sets the 12 rows' text to the site's formatted text, guarded on the
    row's current text (so it applies once, to the damaged text only), and
    clears their MiniLM embedding; the trigger re-derives text_plain and
    text_hash, so their LaBSE embedding becomes stale;
  * inserts the 3 missing verses with the site's text, after 8:1 / 9:29 of
    the same text (verseorigin), and rebuilds CEI2008 in reading order
    (bibleget_rebuild_in_order, 024);
  * updates CEI2008_idx for Esther: its verses_count is written twice (20
    entries) and the first half lacked 8:2 and 9:30 (16 and 31 for chapters
    8 and 9; the second half already had 17 and 32). Both halves become the
    union of both texts' verse numbers: 17 and 32. verses_last (17, 32)
    doesn't change.
Re-embed afterwards: scripts/compute_embeddings.py --version CEI2008, with
the default column and with --column embedding.

The output contains CEI 2008 text (© Fondazione di Religione Santi Francesco
d'Assisi e Caterina da Siena): it is a migration like 023/025/026, reproduced
unaltered from bibbiaedu.it with attribution, for the API's non-commercial use.

Usage:
    python3 scripts/repair_cei2008_esther.py --archive ../CEI2008-bibbiaedu \\
        --dump cei.copy > migrations/038-cei2008-esther-repairs.sql
where cei.copy is the dump described in format_cei2008_from_source.py.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import format_cei2008_from_source as F  # noqa: E402
from markup import require_markup_ok  # noqa: E402

EST = 19
# (chapter, label, origin): rows whose text is replaced by the site's.
REPLACE = [
    (1, "3", "GREEK"), (1, "5", "HEBREW"), (5, "5", "HEBREW"), (7, "4", "GREEK"),
    (7, "8", "HEBREW"), (8, "1", "GREEK"), (9, "24", "HEBREW"), (9, "26", "HEBREW"),
    (9, "28", "HEBREW"), (9, "29", "HEBREW"), (9, "31", "HEBREW"), (9, "32", "HEBREW"),
]
# (chapter, label, origin, after label): verses inserted after a row of the same text.
INSERT = [(8, "2", "GREEK", "1"), (8, "2", "HEBREW", "1"), (9, "30", "HEBREW", "29")]
ROWS_BEFORE = 35720


def site_verse(archive, rows, chapter, label, origin):
    """(text, titles, position) the site prints for this verse of this text."""
    path = next(Path(archive, "html").glob(f"*/Est/{chapter:03d}.html"))
    for block_origin, verses in F.site_blocks(path, rows[(EST, chapter)]):
        if block_origin == origin and label in verses:
            return verses[label]
    sys.exit(f"Est {chapter}:{label} {origin}: not on the site page")


def one_row(rows, chapter, label, origin):
    found = [r for r in rows[(EST, chapter)].get(label, []) if r["origin"] == origin]
    if len(found) != 1:
        sys.exit(f"Est {chapter}:{label} {origin}: expected one row, found {len(found)}")
    return found[0]


def replace_sql(row, text, titles, where):
    if any(titles) and not any(row["titles"]):
        sys.exit(f"{where}: the site has a heading the row lacks; not handled here")
    return (f'    UPDATE "CEI2008" SET text = {F.sql_str(text)}, embedding = NULL '
            f'WHERE "verseID" = {row["vid"]} AND text = {F.sql_str(row["text"])};  -- {where}\n'
            "    GET DIAGNOSTICS n = ROW_COUNT; changed := changed + n;\n")


def insert_sql(after, chapter, label, origin, text, titles, position, where):
    t = (list(titles) + ["", "", ""])[:3]
    pos = position if position is not None else "NULL"
    return (
        f"    SELECT \"verseID\" INTO STRICT anchor FROM \"CEI2008\" WHERE \"verseID\" = {after['vid']};\n"
        '    INSERT INTO "CEI2008" (testament, section, book, chapter, verse, verseorigin, text, title1, title2, title3, title_position)\n'
        f"    SELECT testament, section, {EST}, {chapter}, {int(label)}, '{origin}', {F.sql_str(text)}, "
        f"{F.sql_str(t[0])}, {F.sql_str(t[1])}, {F.sql_str(t[2])}, {pos}\n"
        f'    FROM "CEI2008" WHERE "verseID" = anchor RETURNING "verseID" INTO new_vid;  -- {where}\n'
        "    INSERT INTO cei_ord VALUES (new_vid, anchor + 0.5);\n"
    )


HEADER = """-- Migration 038: CEI2008 Esther repairs (#185). Generated by
-- scripts/repair_cei2008_esther.py from the bibbiaedu.it archive; see its
-- docstring for what each part does and why. Text © Fondazione di Religione
-- Santi Francesco d'Assisi e Caterina da Siena (bibbiaedu.it), reproduced
-- unaltered with attribution.
--
-- Replaces the text of 12 damaged rows (guarded on their current text),
-- inserts Est 8:2 (Greek and Hebrew) and Hebrew 9:30, rebuilds CEI2008 in
-- reading order, and updates CEI2008_idx for Esther. Idempotent: does
-- nothing once Hebrew 8:2 exists. Re-embed CEI2008 afterwards (both columns).

BEGIN;

CREATE TEMP TABLE cei_ord (vid INT PRIMARY KEY, ord NUMERIC NOT NULL) ON COMMIT DROP;

DO $mig$
DECLARE
    n       INT;
    changed INT := 0;
    anchor  INT;
    new_vid INT;
BEGIN
    IF EXISTS (SELECT 1 FROM "CEI2008" WHERE book = 19 AND chapter = 8 AND verse = 2 AND verseorigin = 'HEBREW') THEN
        RAISE NOTICE '038 already applied';
        RETURN;
    END IF;
    IF (SELECT count(*) FROM "CEI2008") <> {rows} THEN
        RAISE EXCEPTION 'CEI2008 has % rows, expected {rows}', (SELECT count(*) FROM "CEI2008");
    END IF;

"""

FOOTER = """
    IF changed <> {n_replace} THEN
        RAISE EXCEPTION 'expected {n_replace} damaged rows to replace, replaced %', changed;
    END IF;

    INSERT INTO cei_ord SELECT "verseID", "verseID" FROM "CEI2008" ON CONFLICT (vid) DO NOTHING;
    PERFORM bibleget_rebuild_in_order('CEI2008', 'cei_ord');
    IF (SELECT count(*) FROM "CEI2008") <> {rows_after} OR (SELECT max("verseID") FROM "CEI2008") <> {rows_after} THEN
        RAISE EXCEPTION 'unexpected row count or verseID range after the rebuild';
    END IF;

    -- Esther's index: one list for both texts (union of their verse numbers),
    -- written twice (20 entries). The first half gains 8:2 and 9:30.
    UPDATE "CEI2008_idx" i SET verses_count = x.cnt || ',' || x.cnt, verses_last = x.last || ',' || x.last
    FROM (
        SELECT string_agg(d::text, ',' ORDER BY chapter) AS cnt, string_agg(m::text, ',' ORDER BY chapter) AS last
        FROM (SELECT chapter, count(DISTINCT verse) AS d, max(verse) AS m FROM "CEI2008" WHERE book = 19 GROUP BY chapter) c
    ) x
    WHERE i.book = 19 AND i.verses_count = '22,23,15,17,14,14,10,16,31,3,22,23,15,17,14,14,10,17,32,3';
    GET DIAGNOSTICS n = ROW_COUNT;
    IF n <> 1 THEN RAISE EXCEPTION 'CEI2008_idx Esther: unexpected verses_count'; END IF;
END
$mig$;

COMMIT;
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--archive", required=True, help="CEI2008-bibbiaedu checkout")
    ap.add_argument("--dump", required=True, help="COPY dump of CEI2008 (see format_cei2008_from_source.py)")
    args = ap.parse_args()
    rows = F.load_dump(args.dump)

    out = [HEADER.replace("{rows}", str(ROWS_BEFORE))]
    for chapter, label, origin in REPLACE:
        where = f"Est {chapter}:{label} {origin}"
        row = one_row(rows, chapter, label, origin)
        text, titles, _ = site_verse(args.archive, rows, chapter, label, origin)
        require_markup_ok(text, where)
        if text == row["text"]:
            sys.exit(f"{where}: already matches the site")
        out.append(replace_sql(row, text, titles, where))
    for chapter, label, origin, after_label in INSERT:
        where = f"Est {chapter}:{label} {origin}"
        if [r for r in rows[(EST, chapter)].get(label, []) if r["origin"] == origin]:
            sys.exit(f"{where}: already exists")
        after = one_row(rows, chapter, after_label, origin)
        text, titles, position = site_verse(args.archive, rows, chapter, label, origin)
        require_markup_ok(text, where)
        out.append(insert_sql(after, chapter, label, origin, text, titles, position, where))
    out.append(FOOTER.replace("{n_replace}", str(len(REPLACE))).replace("{rows_after}", str(ROWS_BEFORE + len(INSERT))))
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
